#!/usr/bin/env bash
# WraithVim uninstaller.
#
# Removes, after confirmation: the generated bootstrap, the distribution
# directory and WraithVim's plugin cache. Your personal configuration
# (~/.config/wraithvim) and all *.bak.* backups are kept unless you pass
# --purge-user-config and confirm. Backups are never deleted.

set -euo pipefail

readonly MARKER="WraithVim bootstrap"

DATA_HOME="${XDG_DATA_HOME:-$HOME/.local/share}"
CONFIG_HOME="${XDG_CONFIG_HOME:-$HOME/.config}"
STATE_HOME="${XDG_STATE_HOME:-$HOME/.local/state}"

DRY_RUN=0
ASSUME_YES=0
PURGE_USER=0
APPNAME="nvim"
TARGET="$DATA_HOME/wraithvim"

info() { printf '==> %s\n' "$*"; }
ok() { printf '  ✓ %s\n' "$*"; }
warn() { printf '  ! %s\n' "$*" >&2; }
die() {
  printf 'error: %s\n' "$*" >&2
  exit 1
}

usage() {
  cat <<'EOF'
Usage: uninstall.sh [options]

  --dry-run             Print actions without changing anything
  --yes                 Do not ask before removing WraithVim's own files
  --appname NAME        Neovim config directory name used at install (default: nvim)
  --dir PATH            Install location (default: $XDG_DATA_HOME/wraithvim)
  --purge-user-config   Also delete ~/.config/wraithvim (asks for explicit
                        confirmation; --yes does not skip it)
  -h, --help            Show this help

Backups (*.bak.*) are never deleted.
EOF
}

run() {
  if ((DRY_RUN)); then
    printf '  [dry-run]'
    printf ' %q' "$@"
    printf '\n'
  else
    "$@"
  fi
}

# confirm "question" -> 0 for yes. Non-interactive sessions answer no.
confirm() {
  ((ASSUME_YES)) && return 0
  if [[ ! -t 0 ]]; then
    warn "no terminal to confirm '$1'; skipping (use --yes)"
    return 1
  fi
  local answer
  read -r -p "  $1 [y/N] " answer
  [[ "$answer" == "y" || "$answer" == "Y" ]]
}

parse_args() {
  while (($#)); do
    case "$1" in
      --dry-run) DRY_RUN=1 ;;
      --yes) ASSUME_YES=1 ;;
      --purge-user-config) PURGE_USER=1 ;;
      --appname)
        [[ $# -ge 2 ]] || die "--appname needs a value"
        APPNAME="$2"
        shift
        ;;
      --dir)
        [[ $# -ge 2 ]] || die "--dir needs a value"
        TARGET="$2"
        shift
        ;;
      -h | --help)
        usage
        exit 0
        ;;
      *) die "unknown option: $1" ;;
    esac
    shift
  done
  [[ "$APPNAME" =~ ^[A-Za-z0-9._-]+$ && "$APPNAME" != "." && "$APPNAME" != ".." ]] || die "invalid --appname"
  # With a trailing slash, a symlinked --dir is not seen as a link and
  # `rm -rf` would delete the linked checkout's contents.
  while [[ "$TARGET" == */ && "$TARGET" != / ]]; do TARGET="${TARGET%/}"; done
}

remove_bootstrap() {
  local config_dir="$CONFIG_HOME/$APPNAME"
  local init="$config_dir/init.lua"
  info "Bootstrap: $init"
  if [[ ! -f "$init" ]]; then
    ok "not present"
    return
  fi
  if ! grep -q "$MARKER" "$init"; then
    warn "$init was not generated by WraithVim; leaving it alone"
    return
  fi
  if confirm "Remove the WraithVim bootstrap $init?"; then
    run rm -f -- "$init"
    # Older bootstraps the installer kept when it regenerated this one.
    local old
    for old in "$init".bak.*; do
      if [[ -f "$old" ]] && grep -q "$MARKER" "$old"; then
        run rm -f -- "$old"
      fi
    done
    # Remove the directory only if the bootstrap was its sole content.
    if ((DRY_RUN == 0)) && [[ -d "$config_dir" && -z "$(ls -A -- "$config_dir")" ]]; then
      rmdir -- "$config_dir"
    fi
    ok "bootstrap removed"
    offer_restore "$config_dir"
  fi
}

# Offer to restore the newest backup of the config directory.
offer_restore() {
  local config_dir="$1" latest=""
  local b
  for b in "$config_dir".bak.*; do
    [[ -e "$b" ]] && latest="$b"
  done
  [[ -n "$latest" ]] || return 0
  if [[ -e "$config_dir" ]] && ((DRY_RUN == 0)); then
    warn "$config_dir still has other files; restore $latest manually if wanted"
    return 0
  fi
  if confirm "Restore your previous configuration from $latest?"; then
    run mv -- "$latest" "$config_dir"
    ok "restored $latest"
  fi
}

remove_distribution() {
  info "Distribution: $TARGET"
  if [[ -L "$TARGET" ]]; then
    if confirm "Remove the symlink $TARGET (the linked checkout is kept)?"; then
      run rm -f -- "$TARGET"
      ok "symlink removed"
    fi
    return
  fi
  if [[ ! -e "$TARGET" ]]; then
    ok "not present"
    return
  fi
  if [[ ! -f "$TARGET/lua/wraithvim/init.lua" ]]; then
    warn "$TARGET does not look like WraithVim; leaving it alone"
    return
  fi
  if confirm "Delete $TARGET?"; then
    run rm -rf -- "$TARGET"
    ok "removed"
  fi
}

remove_cache() {
  local data="$DATA_HOME/$APPNAME/wraithvim"
  local state="$STATE_HOME/$APPNAME/wraithvim"
  info "Plugin cache and logs: $data, $state"
  local any=0 path
  for path in "$data" "$state"; do
    [[ -e "$path" ]] || continue
    any=1
    if confirm "Delete $path?"; then
      run rm -rf -- "$path"
      ok "removed $path"
    fi
  done
  ((any)) || ok "not present"
}

handle_user_config() {
  local dir="$CONFIG_HOME/wraithvim"
  info "User configuration: $dir"
  if [[ ! -e "$dir" ]]; then
    ok "not present"
    return
  fi
  if ((PURGE_USER == 0)); then
    ok "kept (pass --purge-user-config to delete it)"
    return
  fi
  if [[ ! -t 0 ]]; then
    warn "refusing to delete user configuration without an interactive confirmation"
    return
  fi
  local answer
  read -r -p "  Type 'delete' to permanently remove $dir: " answer
  if [[ "$answer" == "delete" ]]; then
    run rm -rf -- "$dir"
    ok "user configuration removed"
  else
    ok "kept"
  fi
}

list_backups() {
  local found=0 b
  for b in "$CONFIG_HOME/$APPNAME".bak.* "$TARGET".bak.*; do
    if [[ -e "$b" ]]; then
      ((found)) || info "Backups (kept):"
      found=1
      printf '  %s\n' "$b"
    fi
  done
  return 0
}

main() {
  parse_args "$@"
  ((DRY_RUN)) && info "Dry run: nothing will be changed"
  remove_bootstrap
  remove_distribution
  remove_cache
  handle_user_config
  list_backups
  info "Done."
}

main "$@"
