local utils = require("wraithvim.core.utils")
local env = require("tests.helpers.env")

describe("core.utils", function()
  describe("merge", function()
    it("deep-merges maps with later tables winning", function()
      local out = utils.merge({ a = 1, n = { x = 1, y = 2 } }, { n = { y = 3 }, b = 2 })
      assert.same({ a = 1, b = 2, n = { x = 1, y = 3 } }, out)
    end)

    it("replaces lists instead of concatenating", function()
      local out = utils.merge({ list = { 1, 2, 3 } }, { list = { 9 } })
      assert.same({ 9 }, out.list)
    end)

    it("keeps map keys when merging an empty table, but replaces lists with it", function()
      local out = utils.merge({ m = { a = 1 }, l = { 1, 2 } }, { m = {}, l = {} })
      assert.same({ a = 1 }, out.m)
      assert.same({}, out.l)
    end)

    it("does not mutate its inputs and ignores nil arguments", function()
      local a = { n = { x = 1 } }
      local out = utils.merge(a, nil, { n = { x = 2 } })
      assert.equals(1, a.n.x)
      assert.equals(2, out.n.x)
    end)
  end)

  it("caches executable lookups and can reset the cache", function()
    assert.is_true(utils.executable("sh"))
    assert.is_false(utils.executable("definitely-not-a-real-binary-wraithvim"))
    utils.reset_executable_cache()
    assert.is_true(utils.executable("sh"))
  end)

  it("runs commands without a shell, passing special characters verbatim", function()
    local dir = env.tmpdir("utils")
    local name = dir .. "/a file; $(touch pwned) 'q\".txt"
    local r = utils.run({ "touch", name })
    assert.equals(0, r.code)
    assert.is_not_nil(vim.uv.fs_stat(name))
    assert.is_nil(vim.uv.fs_stat(dir .. "/pwned"))
    vim.fn.delete(dir, "rf")
  end)

  it("reports a failure instead of throwing for a missing program", function()
    local r = utils.run({ "definitely-not-a-real-binary-wraithvim" })
    assert.are_not.equal(0, r.code)
  end)

  it("rejects string commands", function()
    assert.has_error(function()
      utils.run("echo hi")
    end)
  end)

  it("splits lines and trims", function()
    assert.same({ "a", "b" }, utils.lines("a\n\nb\n"))
    assert.equals("x", utils.trim("x \n"))
  end)

  it("detects large files", function()
    local dir = env.tmpdir("large")
    env.write(dir .. "/big.txt", string.rep("x", 2048))
    vim.cmd.edit(dir .. "/big.txt")
    assert.is_true(utils.is_large_file(0, 1024))
    assert.is_false(utils.is_large_file(0, 4096))
    vim.cmd("bwipeout!")
    vim.fn.delete(dir, "rf")
  end)

  it("creates augroups that clear on re-creation", function()
    local g = utils.augroup("test_group")
    vim.api.nvim_create_autocmd("User", { group = g, pattern = "X", command = "let g:x = 1" })
    utils.augroup("test_group")
    assert.same({}, vim.api.nvim_get_autocmds({ group = "wraithvim_test_group" }))
  end)
end)
